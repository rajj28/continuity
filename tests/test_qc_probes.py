def test_unjudged_measurement_raises_rather_than_passing():
    """A probe whose output has no threshold rule must never look like a pass."""
    rogue = Measurement(key="quality.vibes", value=1.0, unit="ratio", method="x")
    with pytest.raises(UnknownMeasurement):
        check(rogue, "de-DE")
